export function getDynamicIcon(name?: string | null): LucideIcon {
  if (!name) return Sparkles;
  // normalize: case-insensitive check
  if (ICON_MAP[name]) return ICON_MAP[name];
  const found = Object.keys(ICON_MAP).find(
    (k) => k.toLowerCase() === name.toLowerCase().replace(/[-_\s]/g, "")
  );
  return (found ? ICON_MAP[found] : Sparkles) as LucideIcon;
}

export function DynamicIcon({
  name,
  className,
  strokeWidth = 2,
}: {
  name?: string | null;
  className?: string;
  strokeWidth?: number;
}) {
  const Icon = getDynamicIcon(name);
  return <Icon className={className} strokeWidth={strokeWidth} />;
}
